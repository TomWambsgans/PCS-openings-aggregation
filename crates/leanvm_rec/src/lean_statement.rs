// Part of this repository. Follows `crates/evm/src/lean.rs` (a verifier's data as Lean definitions) and
// `crates/leanvm_univariate/tests/lean_format` (the differential vectors). MIT OR Apache-2.0; see NOTICE.md.
//! π2's verifier as `formal/RecStatement` transcribes it: the circuit's tables as Lean data
//! (`formal/RecStatement/RecStatement/Data.lean`, [`render`]) and the vectors of its differential runner
//! ([`header`], [`vector`]).
//!
//! **The data** is what the verifier is built from (`pi2::verifier::Spec::of`): the circuit's shape, its formulas,
//! its (block, role) pairs, the reads of the public data, the public terms, then the instance's constants (π1's
//! contract IV, the setup's root, the circuit's digest) and π1's `PCS_OPEN` calls as the circuit names their words
//! (`spec::CallWord`). Not `σ` and not `κ`: the setup commits them, the digest and the root bind them, and the
//! verifier reads neither. `tests/lean_statement.rs`'s `statement_data_is_current` fails when the checked-in file is
//! not what [`render`] writes for π1-rec3's real circuit (`UPDATE_LEAN=1` rewrites it).
//!
//! **A vector** is one calldata (public input, stream) and what the Rust makes of it: the verdict, the value the
//! verifier requires nonzero, every intermediate value ([`super::pi2::verifier::reduce_traced`]), the public scalars
//! and their pair points, the roots, the four claims, and every `PCS_OPEN` input word for word
//! (`contract::expected_calls`). [`header`] writes the verifier's constants the Lean computes itself (`Spec::of`'s
//! pairs, groups, recursion constants, zero coset and walk; the IV; the layout words; `β_1`; the extension's
//! coordinates), for the runner to compare.

use std::fmt::Write;

use leanvm_flock_gas::VerifierError;
use leanvm_flock_gas::field::E;
use leanvm_flock_gas::transcript::{Checks, KeccakChannel, cantor_beta1, keccak_seed};

use crate::circuit::spec::CallWord;
use crate::pi2::circuit::{Circuit, Coeff, Formula, Lin, Read};
use crate::pi2::contract::{Instance, Recorded, expected_calls};
use crate::pi2::prover::layout_words;
use crate::pi2::verifier::{NAME, Reduced, Spec, extension, reduce_traced, statement_words, tag_walk, to_e};

/// The instance's constants the data carries.
pub struct Constants {
    /// π1's contract IV (`Compiled::pi1_iv`).
    pub pi1_iv: [u8; 32],
    /// The setup's root (`prover::Setup::new(circuit).root()`).
    pub setup_root: [u8; 32],
    /// `circuit.digest()`.
    pub digest: [u8; 32],
}

pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn coeff_text(c: &Coeff) -> String {
    format!(
        "⟨0x{:x}, 0x{:x}, 0x{:x}, {}⟩",
        c.value[0], c.value[1], c.value[2], c.gamma
    )
}

fn lin_text(l: &Lin) -> String {
    let terms: Vec<String> = l
        .terms
        .iter()
        .map(|(c, cell)| format!("({}, {cell})", coeff_text(c)))
        .collect();
    let constant = match &l.constant {
        None => "none".to_string(),
        Some(c) => format!("some {}", coeff_text(c)),
    };
    format!("⟨[{}], {constant}⟩", terms.join(", "))
}

fn formula_text(f: &Formula) -> String {
    let products: Vec<String> = f
        .products
        .iter()
        .map(|(c, a, b)| format!("({}, {}, {})", coeff_text(c), lin_text(a), lin_text(b)))
        .collect();
    format!("⟨{}, [{}]⟩", lin_text(&f.lin), products.join(", "))
}

fn read_text(r: &Read) -> String {
    match r {
        Read::Integer(b) => format!(".integer {b}"),
        Read::Root => ".root".to_string(),
        Read::Scalar => ".scalar".to_string(),
    }
}

fn call_word_text(w: &CallWord) -> String {
    match *w {
        CallWord::Const(bytes) => format!(".const (hexBytes \"{}\")", hex(&bytes)),
        CallWord::Root(i) => format!(".root {i}"),
        CallWord::Element(i) => format!(".element {i}"),
        CallWord::Pair { element, coordinate } => format!(".pair {element} {coordinate}"),
    }
}

/// The formulas per Lean definition: the file's definitions stay small enough to elaborate quickly.
const CHUNK: usize = 16;

/// The Lean file of the circuit's tables and the instance's constants.
pub fn render(circuit: &Circuit, calls: &[Vec<CallWord>], c: &Constants) -> String {
    let mut out = String::new();
    let w = &mut out;
    let spec = Spec::of(circuit);
    writeln!(w, "-- Part of this repository. MIT OR Apache-2.0; see NOTICE.md.").unwrap();
    writeln!(
        w,
        "-- Generated by `crates/leanvm_rec/src/lean_statement.rs` (`render`) from π2's circuit for π1-rec3's real proof. Do not"
    )
    .unwrap();
    writeln!(
        w,
        "-- edit: `UPDATE_LEAN=1 cargo test --release -p leanvm_rec --test lean_statement -- --ignored statement_data_is_current`"
    )
    .unwrap();
    writeln!(w, "-- rewrites it, and the test fails while it is stale.").unwrap();
    writeln!(w, "import RecStatement.Basic").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-!").unwrap();
    writeln!(w, "# π2's circuit for π1-rec3, as its verifier reads it").unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "`pi2::circuit::Circuit` of `circuit::compile::pi2(record_verifier(REFERENCE, Flock(FLOCK_REC3), Point), D16v)` through"
    )
    .unwrap();
    writeln!(
        w,
        "`pi2::adapt`: `2^{}` positions, rows of `2^{}`, {} formulas, {} (block, role) pairs ({} pull-less) in {} groups, {} reads,",
        circuit.log_n,
        circuit.log_row,
        circuit.formulas.len(),
        circuit.pairs.len(),
        spec.pull_less.len(),
        spec.groups.len(),
        circuit.reads.len()
    )
    .unwrap();
    writeln!(
        w,
        "{} public terms ({} of them the zero coset); π1's {} `PCS_OPEN` calls. Not `σ`, not `κ` (the setup's root and",
        circuit.public.len(),
        spec.zero_coset.as_ref().map_or(0, |(_, k, _)| 1usize << k),
        calls.len()
    )
    .unwrap();
    writeln!(
        w,
        "the circuit's digest bind them; the verifier reads neither). Data only."
    )
    .unwrap();
    writeln!(w, "-/").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "namespace RecStatement.Data").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "open RecStatement").unwrap();
    writeln!(w).unwrap();
    let chunks: Vec<&[Formula]> = circuit.formulas.chunks(CHUNK).collect();
    for (k, chunk) in chunks.iter().enumerate() {
        writeln!(w, "/-- Formulas {}..{}. -/", k * CHUNK, k * CHUNK + chunk.len()).unwrap();
        writeln!(w, "def formulas{k} : List Formula := [").unwrap();
        let items: Vec<String> = chunk.iter().map(|f| format!("  {}", formula_text(f))).collect();
        writeln!(w, "{}]", items.join(",\n")).unwrap();
        writeln!(w).unwrap();
    }
    let names: Vec<String> = (0..chunks.len()).map(|k| format!("formulas{k}")).collect();
    writeln!(w, "/-- The formulas (`Circuit::formulas`). -/").unwrap();
    writeln!(w, "def formulas : List Formula := {}", names.join(" ++ ")).unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- The (block, role) pairs (`Circuit::pairs`): first row, rows' log, role, formula, pulls. -/"
    )
    .unwrap();
    writeln!(w, "def pairs : List Pair := [").unwrap();
    let items: Vec<String> = circuit
        .pairs
        .iter()
        .map(|p| {
            format!(
                "  ⟨{}, {}, {}, {}, {}⟩",
                p.first_row, p.log_rows, p.role, p.formula, p.pulls
            )
        })
        .collect();
    writeln!(w, "{}]", items.join(",\n")).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- The public data read from the stream (`Circuit::reads`). -/").unwrap();
    writeln!(
        w,
        "def reads : List Read := [{}]",
        circuit.reads.iter().map(read_text).collect::<Vec<_>>().join(", ")
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- The public side (`Circuit::public`): each term's tag and value. -/"
    )
    .unwrap();
    writeln!(w, "def publicTerms : List PublicTerm := [").unwrap();
    let items: Vec<String> = circuit
        .public
        .iter()
        .map(|t| format!("  ⟨{}, {}⟩", t.tag, lin_text(&t.value)))
        .collect();
    writeln!(w, "{}]", items.join(",\n")).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- **π2's circuit** as its verifier reads it. -/").unwrap();
    writeln!(
        w,
        "def circuit : Circuit := ⟨{}, {}, formulas, pairs, reads, publicTerms⟩",
        circuit.log_n, circuit.log_row
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- π1's contract IV (`Compiled::pi1_iv`: π1-rec3's at the reference setup roots). -/"
    )
    .unwrap();
    writeln!(w, "def pi1Iv : List UInt8 := hexBytes \"{}\"", hex(&c.pi1_iv)).unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- The setup's root (`prover::Setup::new(circuit).root()`: the commitment of `κ`, `κ + σ`). -/"
    )
    .unwrap();
    writeln!(w, "def setupRoot : List UInt8 := hexBytes \"{}\"", hex(&c.setup_root)).unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- The circuit's digest (`Circuit::digest`: its encoding with `σ`'s and `κ`'s hashes). -/"
    )
    .unwrap();
    writeln!(w, "def digest : List UInt8 := hexBytes \"{}\"", hex(&c.digest)).unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- π1's `PCS_OPEN` calls as the circuit names their words (`spec::Circuit::calls`). -/"
    )
    .unwrap();
    writeln!(w, "def pi1Calls : List (List CallWord) := [").unwrap();
    let items: Vec<String> = calls
        .iter()
        .map(|call| {
            format!(
                "  [{}]",
                call.iter().map(call_word_text).collect::<Vec<_>>().join(",\n   ")
            )
        })
        .collect();
    writeln!(w, "{}]", items.join(",\n")).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "end RecStatement.Data").unwrap();
    out
}

fn e_text(x: E) -> String {
    format!("{:x}:{:x}:{:x}", x.c0, x.c1, x.c2)
}

fn list_text(xs: &[E]) -> String {
    let mut s = xs.len().to_string();
    for &x in xs {
        s.push(' ');
        s.push_str(&e_text(x));
    }
    s
}

/// The verifier's constants, for the runner to compare with the Lean's: `Spec::of`'s parts, the IV, the layout
/// words, `β_1`, the extension's coordinates and scale, the stream's length.
pub fn header(inst: &Instance, recorded: &Recorded) -> String {
    let spec = inst.spec;
    let mut out = String::new();
    let w = &mut out;
    let k = |x: primitives::field::F64| E::new(x.0, 0, 0);
    writeln!(
        w,
        "SPEC pairs {}{}",
        spec.pairs.len(),
        spec.pairs
            .iter()
            .map(|p| format!(" {} {}", p.log_rows, e_text(k(p.z))))
            .collect::<String>()
    )
    .unwrap();
    writeln!(
        w,
        "SPEC c {}",
        list_text(&spec.c.iter().map(|&x| k(x)).collect::<Vec<E>>())
    )
    .unwrap();
    let groups: Vec<String> = spec
        .groups
        .iter()
        .map(|g| {
            format!(
                " {} {} {}{}",
                g.role,
                g.pulls as u8,
                g.pairs.len(),
                g.pairs.iter().map(|p| format!(" {p}")).collect::<String>()
            )
        })
        .collect();
    writeln!(w, "SPEC groups {}{}", spec.groups.len(), groups.concat()).unwrap();
    writeln!(
        w,
        "SPEC pullless {}{}",
        spec.pull_less.len(),
        spec.pull_less.iter().map(|p| format!(" {p}")).collect::<String>()
    )
    .unwrap();
    writeln!(
        w,
        "SPEC public {}{}",
        spec.public.len(),
        spec.public.iter().map(|t| format!(" {}", t.tag)).collect::<String>()
    )
    .unwrap();
    match &spec.zero_coset {
        None => writeln!(w, "SPEC coset none").unwrap(),
        Some((tag, kk, a)) => writeln!(
            w,
            "SPEC coset {tag} {kk} {}",
            list_text(&a.iter().map(|&x| k(x)).collect::<Vec<E>>())
        )
        .unwrap(),
    }
    let walk = tag_walk(&spec.public);
    writeln!(
        w,
        "SPEC walk {}{}",
        walk.len(),
        walk.iter().map(|j| format!(" {j}")).collect::<String>()
    )
    .unwrap();
    writeln!(w, "SPEC maxgamma {}", spec.max_gamma).unwrap();
    writeln!(w, "CONST iv {}", hex(&inst.iv)).unwrap();
    let words = layout_words(spec.log_n);
    writeln!(
        w,
        "CONST layoutwords {} {} {}",
        hex(&words[0]),
        hex(&words[1]),
        hex(&words[2])
    )
    .unwrap();
    writeln!(w, "CONST beta1 {}", e_text(cantor_beta1())).unwrap();
    let ([y0, y1], scale) = extension();
    writeln!(
        w,
        "CONST extension {} {} {}",
        e_text(to_e(y0)),
        e_text(to_e(y1)),
        e_text(to_e(scale))
    )
    .unwrap();
    writeln!(w, "CONST streamlen {}", recorded.stream_len).unwrap();
    out
}

/// The Rust verifier on `E` with the Keccak-256 chain (`contract::rust_verifier`), every check collected, and its
/// trace.
pub type Traced = (Result<(Reduced<E>, Vec<E>), VerifierError>, Vec<(&'static str, Vec<E>)>);

pub fn traced(inst: &Instance, public_input: &[u8; 32], stream: &[u8]) -> Traced {
    let seed = keccak_seed(&NAME, &inst.iv, public_input);
    let mut channel = KeccakChannel::new(
        seed,
        stream,
        Checks::Collect {
            zero: vec![],
            nonzero: vec![],
        },
    );
    let mut steps: Vec<(&'static str, Vec<E>)> = Vec::new();
    let result = reduce_traced(
        inst.spec,
        statement_words(public_input),
        &mut channel,
        &mut |name, values| steps.push((name, values.to_vec())),
    )
    .and_then(|reduced| {
        channel.finish()?;
        let Checks::Collect { nonzero, .. } = &channel.checks else {
            unreachable!()
        };
        Ok((reduced, nonzero.clone()))
    });
    (result, steps)
}

fn error_name(e: &VerifierError) -> String {
    format!("{e:?}")
}

/// One vector: the calldata, the Rust verifier's verdict, every value it computes, the claims, and the `PCS_OPEN`
/// inputs; `contract`, when given, the inputs the compiled contract called `PCS_OPEN` with (revm, every call
/// attested), which must be the Rust's.
pub fn vector(
    name: &str,
    inst: &Instance,
    recorded: &Recorded,
    public_input: &[u8; 32],
    stream: &[u8],
    contract: Option<&[Vec<u8>]>,
) -> String {
    let mut out = String::new();
    let w = &mut out;
    writeln!(w, "VECTOR {name}").unwrap();
    writeln!(w, "PUBLIC {}", hex(public_input)).unwrap();
    writeln!(w, "STREAM {}", hex(stream)).unwrap();
    let (result, steps) = traced(inst, public_input, stream);
    for (step, values) in &steps {
        writeln!(w, "TRACE {} {}", step.replace(' ', "_"), list_text(values)).unwrap();
    }
    match result {
        Err(e) => writeln!(w, "RESULT {}", error_name(&e)).unwrap(),
        Ok((reduced, nonzero)) => {
            writeln!(w, "RESULT ok").unwrap();
            writeln!(w, "NONZERO {}", list_text(&nonzero)).unwrap();
            writeln!(w, "PUBLICS {}", list_text(&reduced.public)).unwrap();
            writeln!(
                w,
                "PAIRPOINTS {}",
                list_text(&reduced.pair_points.iter().flatten().copied().collect::<Vec<E>>())
            )
            .unwrap();
            writeln!(
                w,
                "ROOTS {}",
                list_text(&reduced.roots.iter().flatten().copied().collect::<Vec<E>>())
            )
            .unwrap();
            for (claim, (point, value)) in [
                ("witness", &reduced.witness),
                ("quotient", &reduced.quotient),
                ("sum", &reduced.sum),
                ("setup", &reduced.setup),
            ] {
                writeln!(w, "CLAIM {claim} {} {}", list_text(point), e_text(*value)).unwrap();
            }
            let calls = expected_calls(inst, recorded, &reduced, stream);
            writeln!(w, "CALLS {}", calls.len()).unwrap();
            for call in &calls {
                writeln!(
                    w,
                    "CALL {}{}",
                    call.len(),
                    call.iter().map(|word| format!(" {}", hex(word))).collect::<String>()
                )
                .unwrap();
            }
            if let Some(made) = contract {
                let expected: Vec<Vec<u8>> = calls.iter().map(|words| words.concat()).collect();
                let all_nonzero = nonzero.iter().all(|&x| x != E::default());
                if all_nonzero {
                    assert_eq!(
                        made,
                        &expected[..],
                        "{name}: the contract's PCS_OPEN inputs are the Rust's"
                    );
                } else {
                    assert!(made.is_empty(), "{name}: the contract reverts before its calls");
                }
                writeln!(w, "CONTRACT {}", made.len()).unwrap();
            }
        }
    }
    writeln!(w, "END").unwrap();
    out
}
