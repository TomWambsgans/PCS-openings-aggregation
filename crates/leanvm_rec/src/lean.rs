//! π1-rec3's recorded graph as Lean data (`formal/RecGraph/RecGraph/Emitted.lean`), and the test vectors of
//! `formal/RecGraph`'s differential runner.
//!
//! The graph is `leanvm_univariate::contract::record_verifier` at the reference shape with `FLOCK_REC3` (π1-rec3: the
//! recursion's inner proof) and the point-claim ABI (`Claims::Point`): the graph π2's circuit is compiled from
//! (`crate::pi2::pi1`, `crate::circuit`).
//! [`render`] writes its nodes (in creation order), the values it requires zero and nonzero, the ring-weight
//! kernels' operands, the five `PCS_OPEN` calls' words and the stream's length as Lean definitions; the test
//! `tests/lean_graph.rs`'s `graph_lean_is_current` fails when the checked-in file is not what [`render`] writes now
//! (`UPDATE_LEAN=1` rewrites it). [`vector`] writes one stream and what the Rust makes of it twice: the graph
//! evaluated by [`crate::eval`] (the `PCS_OPEN` inputs and the checks' values), and the Rust verifier on `E`
//! (`leanvm_univariate::contract::rust_verifier_with`).

use std::fmt::Write;

use leanvm_flock_gas::evm::codegen::Word;
use leanvm_flock_gas::evm::machine::element_word;
use leanvm_flock_gas::evm::record::Node;
use leanvm_flock_gas::field::E;
use leanvm_flock_gas::shapes::PROGRAM_IV;
use leanvm_flock_gas::transcript::keccak_seed;
use leanvm_univariate::claims::Commitment;
use leanvm_univariate::contract::{NAME, Recorded, calls, layout_words, record_verifier, rust_verifier_with};
use leanvm_univariate::{Blake2s, Claims, FLOCK_REC3, Opening, Reduced};

use crate::REFERENCE;
use crate::eval::{call_inputs, checks, evaluate};

/// The nodes of one Lean definition: the file's definitions stay small enough to elaborate quickly.
const CHUNK: usize = 1000;

/// π1-rec3's verifier at the reference shape, recorded: the graph π2's circuit is compiled from. Records π1's
/// verifier: run it on a thread with a deep stack.
pub fn recorded() -> Recorded {
    record_verifier(&REFERENCE, Blake2s::Flock(FLOCK_REC3), Claims::Point)
}

/// The contract's IV (the program's, at the reference setup roots, for the recorded variant), which the transcript's
/// seed hashes.
pub fn reference_iv(recorded: &Recorded) -> [u8; 32] {
    recorded.iv(&PROGRAM_IV)
}

fn word_nat(bytes: &[u8; 32]) -> String {
    let digits: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
    let trimmed = digits.trim_start_matches('0');
    format!("0x{}", if trimmed.is_empty() { "0" } else { trimmed })
}

fn list<T>(items: impl IntoIterator<Item = T>, show: impl Fn(T) -> String) -> String {
    let items: Vec<String> = items.into_iter().map(show).collect();
    format!("[{}]", items.join(", "))
}

fn node_text(node: &Node) -> String {
    match *node {
        Node::Const([c0, c1, c2]) => format!("const 0x{c0:x} 0x{c1:x} 0x{c2:x}"),
        Node::Statement(k) => format!("statement {k}"),
        Node::Input { offset, len } => format!("input {offset} {len}"),
        Node::Add(a, b) => format!("add {a} {b}"),
        Node::Mul(a, b) => format!("mul {a} {b}"),
        Node::Seed => "seed".to_string(),
        Node::Hash(state, from, to) => format!("hash {state} {from} {to}"),
        Node::Low(h) => format!("low {h}"),
        Node::Narrow(h) => format!("narrow {h}"),
        Node::Bits(v, shift, width) => format!("bits {v} {shift} {width}"),
        Node::RingWeight(kernel, n) => format!("ringWeight {kernel} {n}"),
    }
}

fn word_text(word: &Word) -> String {
    match word {
        Word::Node(id) => format!("Word.node {id}"),
        Word::Const(bytes) => format!("Word.const {}", word_nat(bytes)),
        Word::Stream(at) => format!("Word.stream {at}"),
        Word::Stored(_) => panic!("π1's contract stores nothing: the setup roots are code constants"),
    }
}

/// The Lean file: the graph's nodes in creation order, its checks, its ring-weight kernels, the words of its five
/// `PCS_OPEN` calls and the stream's length.
pub fn render(recorded: &Recorded) -> String {
    let graph = &recorded.graph;
    let call_words = calls(recorded);
    let hashes = graph.nodes.iter().filter(|n| matches!(n, Node::Hash(..))).count();
    let ops = graph
        .nodes
        .iter()
        .filter(|n| matches!(n, Node::Add(..) | Node::Mul(..)))
        .count();
    let mut out = String::new();
    let w = &mut out;
    writeln!(w, "-- Part of this repository. MIT OR Apache-2.0; see NOTICE.md.").unwrap();
    writeln!(
        w,
        "-- Generated by `crates/leanvm_rec/src/lean.rs` (`render`) from π1-rec3's recorded verifier. Do not edit:"
    )
    .unwrap();
    writeln!(
        w,
        "-- `UPDATE_LEAN=1 cargo test --release -p leanvm_rec --test lean_graph graph_lean_is_current` rewrites it, and the"
    )
    .unwrap();
    writeln!(w, "-- test fails while it is stale.").unwrap();
    writeln!(w, "import RecGraph.Node").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-!").unwrap();
    writeln!(w, "# π1-rec3's recorded graph").unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "`leanvm_univariate::contract::record_verifier` at the reference shape (`leanvm_rec::REFERENCE`), with"
    )
    .unwrap();
    writeln!(
        w,
        "`Blake2s::Flock(FLOCK_REC3)` (π1-rec3: `FsShape::Rec3`, `Slices::TowerWalk`) and `Claims::Point`: {} nodes ({ops} additions",
        graph.nodes.len()
    )
    .unwrap();
    writeln!(
        w,
        "and products of `E`, {hashes} Keccak-256 calls), {} values required zero and {} nonzero, {} ring-weight kernels, {} `PCS_OPEN`",
        graph.zero.len(),
        graph.nonzero.len(),
        graph.kernels.len(),
        call_words.len()
    )
    .unwrap();
    writeln!(
        w,
        "calls of {} words, a stream of {} bytes.",
        list(call_words.iter().map(Vec::len), |n| n.to_string()),
        recorded.stream_len
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "Data only: nothing here is evaluated by the kernel; `RecGraph.Semantics` gives it its meaning, and the differential"
    )
    .unwrap();
    writeln!(
        w,
        "runner (`RecGraphTest/Runner.lean`) evaluates it with `lake env lean`."
    )
    .unwrap();
    writeln!(w, "-/").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "namespace RecGraph.Emitted").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "open RecGraph Node").unwrap();
    writeln!(w).unwrap();
    let chunks: Vec<&[Node]> = graph.nodes.chunks(CHUNK).collect();
    for (c, chunk) in chunks.iter().enumerate() {
        writeln!(
            w,
            "/-- Nodes {} to {}, in the order recorded. -/",
            c * CHUNK,
            c * CHUNK + chunk.len() - 1
        )
        .unwrap();
        writeln!(w, "def nodes{c} : List Node := [").unwrap();
        for (i, node) in chunk.iter().enumerate() {
            let comma = if i + 1 < chunk.len() { "," } else { "" };
            writeln!(w, "  {}{comma}", node_text(node)).unwrap();
        }
        writeln!(w, "]").unwrap();
        writeln!(w).unwrap();
    }
    writeln!(
        w,
        "/-- The nodes, in the order recorded: node `i` reads only nodes below `i`. -/"
    )
    .unwrap();
    let parts: Vec<String> = (0..chunks.len()).map(|c| format!("nodes{c}")).collect();
    writeln!(w, "def nodes : Array Node := ({}).toArray", parts.join(" ++ ")).unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- The values the verifier requires zero, in the order required. -/"
    )
    .unwrap();
    writeln!(
        w,
        "def zero : List Nat := {}",
        list(graph.zero.iter(), |(id, _)| id.to_string())
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- The values the verifier requires nonzero, in the order required. -/"
    )
    .unwrap();
    writeln!(
        w,
        "def nonzero : List Nat := {}",
        list(graph.nonzero.iter(), |(id, _)| id.to_string())
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- Each ring-weight kernel's operands: the point, `1 + r`, the map (`Node.ringWeight k n`: `n` coordinates). -/"
    )
    .unwrap();
    writeln!(w, "def kernels : Array (List Nat) := #[").unwrap();
    for (k, kernel) in graph.kernels.iter().enumerate() {
        let comma = if k + 1 < graph.kernels.len() { "," } else { "" };
        writeln!(w, "  {}{comma}", list(kernel.iter(), |x| x.to_string())).unwrap();
    }
    writeln!(w, "]").unwrap();
    writeln!(w).unwrap();
    for (c, call) in call_words.iter().enumerate() {
        writeln!(w, "/-- The words of `PCS_OPEN` call {c}. -/").unwrap();
        writeln!(w, "def call{c} : List Word := [").unwrap();
        for (i, word) in call.iter().enumerate() {
            let comma = if i + 1 < call.len() { "," } else { "" };
            writeln!(w, "  {}{comma}", word_text(word)).unwrap();
        }
        writeln!(w, "]").unwrap();
        writeln!(w).unwrap();
    }
    let call_names: Vec<String> = (0..call_words.len()).map(|c| format!("call{c}")).collect();
    writeln!(
        w,
        "/-- The `PCS_OPEN` calls' words, in call order: `C1`, `C2`, the setup. -/"
    )
    .unwrap();
    writeln!(w, "def calls : List (List Word) := [{}]", call_names.join(", ")).unwrap();
    writeln!(w).unwrap();
    writeln!(
        w,
        "/-- The stream's bytes (calldata after the selector and the public input). -/"
    )
    .unwrap();
    writeln!(w, "def streamLen : Nat := {}", recorded.stream_len).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- Where the stream holds `C1`'s and `C2`'s roots. -/").unwrap();
    writeln!(
        w,
        "def rootsAt : List Nat := {}",
        list(recorded.roots_at.iter(), |x| x.to_string())
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(w, "/-- **π1-rec3's graph.** -/").unwrap();
    writeln!(w, "def graph : Graph where").unwrap();
    for field in ["nodes", "zero", "nonzero", "kernels", "calls", "streamLen"] {
        writeln!(w, "  {field} := {field}").unwrap();
    }
    writeln!(w).unwrap();
    writeln!(w, "end RecGraph.Emitted").unwrap();
    out
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn element(x: E) -> String {
    format!("{:x}:{:x}:{:x}", x.c0, x.c1, x.c2)
}

fn elements(xs: &[E]) -> String {
    let mut out = xs.len().to_string();
    for &x in xs {
        out.push(' ');
        out.push_str(&element(x));
    }
    out
}

fn number(n: u64) -> [u8; 32] {
    let mut bytes = [0u8; 32];
    bytes[24..].copy_from_slice(&n.to_be_bytes());
    bytes
}

/// The `PCS_OPEN` inputs of the Rust verifier's point claims, as the contract writes them
/// (`leanvm_univariate::contract::calls` on `E`: point claims only, and `A0`, `B0` only without the walk).
fn native_calls(reduced: &Reduced<E>, recorded: &Recorded, stream: &[u8]) -> Vec<Vec<u8>> {
    let layouts = layout_words(&recorded.shape);
    let roots = recorded.roots;
    let root = |at: usize| -> [u8; 32] { stream[at..at + 32].try_into().expect("a root") };
    let mut out = Vec::new();
    for (commitment, opening) in &reduced.openings {
        let (r, layout) = match commitment {
            Commitment::C1 => (root(recorded.roots_at[0]), layouts[0]),
            Commitment::C2 => (root(recorded.roots_at[1]), layouts[1]),
            Commitment::Setup => (roots.f, layouts[2]),
        };
        let Opening::Point {
            point,
            value,
            bit_slice: None,
        } = opening
        else {
            panic!("π1-rec3's openings are point claims")
        };
        let mut words = vec![r, layout, number(1)];
        words.extend(point.iter().map(|&x| element_word(x)));
        words.push(element_word(*value));
        out.push(words.concat());
    }
    if let Some(matrices) = reduced.matrices.as_ref() {
        for (r, layout, value) in [(roots.a0, layouts[3], matrices.a), (roots.b0, layouts[4], matrices.b)] {
            let mut words = vec![r, layout, number(1)];
            words.extend(matrices.point.iter().map(|&x| element_word(x)));
            words.push(element_word(value));
            out.push(words.concat());
        }
    }
    out
}

/// One vector of the runner: the stream, and what the evaluated graph ([`crate::eval`]: its `PCS_OPEN` inputs and
/// its checks' values) and the Rust verifier on `E` make of it. `stream` is of the graph's length.
pub fn vector(id: &str, recorded: &Recorded, public: &[u8; 32], stream: &[u8]) -> String {
    assert_eq!(stream.len(), recorded.stream_len, "a stream of the graph's length");
    let iv = reference_iv(recorded);
    let seed = keccak_seed(&NAME, &iv, public);
    let values = evaluate(&recorded.graph, seed, public, stream);
    let inputs = call_inputs(recorded, &values, stream);
    let (zero, nonzero) = checks(&recorded.graph, &values);
    let mut out = String::new();
    let w = &mut out;
    writeln!(w, "VECTOR {id}").unwrap();
    writeln!(w, "IV {}", hex(&iv)).unwrap();
    writeln!(w, "PUBLIC {}", hex(public)).unwrap();
    writeln!(w, "STREAM {}", hex(stream)).unwrap();
    for call in &inputs {
        writeln!(w, "EVALCALL {}", hex(call)).unwrap();
    }
    writeln!(w, "EVALZEROS {}", elements(&zero)).unwrap();
    writeln!(w, "EVALNONZEROS {}", elements(&nonzero)).unwrap();
    match rust_verifier_with(
        &recorded.shape,
        &PROGRAM_IV,
        &recorded.roots,
        public,
        stream,
        recorded.blake2s,
        Claims::Point,
    ) {
        Ok((reduced, zero, nonzero)) => {
            writeln!(w, "NATIVE ok").unwrap();
            for call in native_calls(&reduced, recorded, stream) {
                writeln!(w, "NATIVECALL {}", hex(&call)).unwrap();
            }
            writeln!(w, "NATIVEZEROS {}", elements(&zero)).unwrap();
            writeln!(w, "NATIVENONZEROS {}", elements(&nonzero)).unwrap();
        }
        Err(e) => writeln!(w, "NATIVE err {e:?}").unwrap(),
    }
    writeln!(w, "END").unwrap();
    out
}
